#!/usr/bin/env node
/**
 * Build `cordis.patch.yml` from a base-prompt Markdown file.
 *
 * The Efficient Mode preset's base prompt is a `{{variable}}` template: the
 * source file's bracketed placeholders are replaced here, one exact match per
 * entry in REPLACEMENTS, and the result is embedded as the `persona.prefix`
 * literal block scalar. Nothing else in the source is touched.
 *
 * Usage:
 *   node scripts/build-patch.mjs ["/path/to/System prompt.md"]
 *
 * The default source is the file this preset was authored from. Re-run this
 * after editing that file, then reinstall the bundle so the profile picks up
 * the new patch.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const PACKAGE_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = process.argv[2] ?? '/home/zilorn/Documents/System prompt.md'
const TARGET = resolve(PACKAGE_ROOT, 'cordis.patch.yml')

/**
 * Placeholder substitutions, applied in order and each required to match.
 * The keys are the source file's literal placeholder text; the values are the
 * prompt variables `index.js` registers.
 */
const REPLACEMENTS = [
  ['Current branch: [branch]', 'Current branch: {{git_branch}}'],
  ['Main branch (you will usually use this for PRs): [branch]', 'Main branch (you will usually use this for PRs): {{git_main_branch}}'],
  ['Git user: [user_name]', 'Git user: {{git_user}}'],
  ['Status:\n(clean)', 'Status:\n{{git_status}}'],
  ['[commits(3)]', '{{git_commits}}'],
  ['`[XXX]`', '`{{working_directory}}`'],
  ['- Is a git repository: [true]', '- Is a git repository: {{is_git_repository}}'],
  ['- Platform: [darwin]', '- Platform: {{platform}}'],
  ['- Shell: [shell]', '- Shell: {{shell}}'],
  ['- OS Version: [OS]', '- OS Version: {{os_version}}'],
  ["Today's date is [2026-09-27].", "Today's date is {{today}}."],
]

/** Indentation of the template text inside the patch document. */
const TEMPLATE_INDENT = 16

let text = readFileSync(SOURCE, 'utf8').replace(/\r\n/g, '\n').replace(/\n+$/, '')

for (const [from, to] of REPLACEMENTS) {
  if (!text.includes(from)) throw new Error(`${SOURCE}: placeholder not found: ${JSON.stringify(from)}`)
  text = text.replace(from, to)
}

const leftovers = [...new Set([...text.matchAll(/\[[^\]\n]*\]/g)].map((match) => match[0]))]
console.log('bracket groups left in the template (all prose, none a placeholder):')
for (const item of leftovers) console.log(`  ${item}`)

const indented = text
  .split('\n')
  .map((line) => (line.length === 0 ? '' : ' '.repeat(TEMPLATE_INDENT) + line))
  .join('\n')

const document = `# 高效模式 (Efficient Mode): one \`@deepseek-ai/dsh-agent-preset\` declaration
# plus the Host row that supplies the dynamic facts its base prompt
# interpolates. \`install_bundle\` installs this package into the profile; the
# declaration then appears on the Agent-preset roster as \`efficient\`.
#
# Generated by scripts/build-patch.mjs from the base-prompt template; edit that
# template and re-run the script rather than hand-editing the prefix block.
- insert:
    - id: preset-efficient
      name: '@deepseek-ai/dsh-agent-preset'
      config:
        id: efficient
        name: 高效模式
        description: 高效模式：以 System prompt 模板为基础提示词，git 与运行环境信息按会话动态填充。
        order: 5
        plugins:
          # Dynamic facts. Registers every {{...}} reference the persona template
          # below interpolates; this is the bundle's own Host plugin.
          - id: prompt-facts
            name: '@local/dsh-efficient-mode'
          # Base prompt. \`complete: true\` makes the rendered prefix this agent's
          # whole system prompt, so the template alone defines the identity.
          - id: persona
            name: '@deepseek-ai/dsh-persona'
            config:
              complete: true
              prefix: |
${indented}
          # Capabilities, mirroring the shipped \`standard\` preset so the mode is
          # usable; README.md lists the rows deliberately left out.
          - id: tool-bash
            name: '@deepseek-ai/dsh-tool-bash'
            disabled: !!js process.platform === 'win32'
          - id: tool-pwsh
            name: '@deepseek-ai/dsh-tool-pwsh'
            disabled: !!js process.platform !== 'win32'
          - id: tool-fs
            name: '@deepseek-ai/dsh-tool-fs'
          - id: tool-fs-search
            name: '@deepseek-ai/dsh-tool-fs-search'
          - id: tool-jobs
            name: '@deepseek-ai/dsh-tool-jobs'
          - id: tool-schedule
            name: '@deepseek-ai/dsh-tool-schedule'
          - id: skill-filesystem
            name: '@deepseek-ai/dsh-skill-filesystem'
          - id: tool-skill
            name: '@deepseek-ai/dsh-tool-skill'
          - id: command-goal
            name: '@deepseek-ai/dsh-command-goal'
          - id: tool-goal
            name: '@deepseek-ai/dsh-tool-goal'
          - id: planning
            name: cordis:group
            group: true
            isolate:
              planMode: true
            config:
              - id: plan-mode
                name: '@deepseek-ai/dsh-plan-mode'
          - id: compaction
            name: cordis:group
            group: true
            isolate:
              compaction: true
              toolResultPruner: true
            config:
              - id: compaction-basic
                name: '@deepseek-ai/dsh-compaction-basic'
              - id: command-compact
                name: '@deepseek-ai/dsh-command-compact'
              - id: tool-result-pruner
                name: '@deepseek-ai/dsh-compaction-tool-result-pruner'
                config:
                  thresholdChars: 8192
                  headChars: 4096
                  tailChars: 1024
          - id: delegation
            name: cordis:group
            group: true
            config:
              - id: tool-subagent-control
                name: '@deepseek-ai/dsh-tool-subagent-control'
              - id: tool-subagent-list-agents
                name: '@deepseek-ai/dsh-tool-subagent-control/list-agents'
              - id: tool-subagent
                name: '@deepseek-ai/dsh-tool-subagent'
                config:
                  provider: spawn
                  toolName: subagent
                  modelSelectionSettings: true
                  backgroundMode: continuable
                  toolFilter:
                    deny:
                      - schedule_create
                      - schedule_delete
                      - schedule_list
                      - schedule_update
              - id: tool-subagent-fork
                name: '@deepseek-ai/dsh-tool-subagent'
                config:
                  provider: fork
                  toolName: subagent_fork
                  backgroundMode: continuable
                  toolFilter:
                    deny:
                      - schedule_create
                      - schedule_delete
                      - schedule_list
                      - schedule_update
          - id: tool-ask-user
            name: '@deepseek-ai/dsh-tool-ask-user'
          - id: tool-todo
            name: '@deepseek-ai/dsh-tool-todo'
            config:
              allowParallelInProgress: true
          - id: tool-web
            name: '@deepseek-ai/dsh-tool-web'
            config:
              fetch: true
              searchTimeoutMs: 60000
          - id: present
            name: '@deepseek-ai/dsh-tool-present'
`

writeFileSync(TARGET, document)
console.log(`wrote ${TARGET} (${document.split('\n').length} lines) from ${SOURCE}`)
